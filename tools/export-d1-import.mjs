import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const toolDir = dirname(fileURLToPath(import.meta.url))
const projectDir = resolve(toolDir, '..')
const fixturePath = resolve(projectDir, 'server/data/legacy-content.json')
const outputPath = resolve(projectDir, 'exports/legacy-import.sql')

function sql(value) {
  if (value === null || value === undefined) return 'NULL'
  if (typeof value === 'number') return String(value)
  return `'${String(value).replaceAll("'", "''")}'`
}

function json(value) {
  return sql(JSON.stringify(value))
}

const fixture = JSON.parse(await readFile(fixturePath, 'utf8'))
const contents = [...fixture.reports, ...fixture.essays]
const statements = [
  '-- Generated by tools/export-d1-import.mjs. Do not edit by hand.',
  '-- Idempotent: existing rows with the same source_key are preserved.',
  'PRAGMA foreign_keys = ON;'
]

for (const item of contents) {
  const values = [
    item.id,
    item.type,
    item.title,
    item.summary,
    item.format,
    item.bodyMarkdown,
    item.coverAssetId,
    item.posterAssetId,
    item.authorMemberId,
    item.authorDisplayName,
    JSON.stringify(item.tags),
    item.periodStart,
    item.periodEnd,
    item.stats == null ? null : JSON.stringify(item.stats),
    item.status,
    item.version,
    item.contentHash,
    item.publishedAt,
    item.updatedAt,
    item.sourceKey,
    JSON.stringify(item.sourceRecord)
  ]

  statements.push(`INSERT INTO contents (
  id, type, title, summary, format, body_markdown,
  cover_asset_id, poster_asset_id, author_member_id, author_display_name,
  tags_json, period_start, period_end, stats_json, status, version,
  content_hash, published_at, updated_at, source_key, source_record_json
) VALUES (${values.map(sql).join(', ')})
ON CONFLICT(source_key) DO NOTHING;`)

  const snapshot = {
    id: item.id,
    type: item.type,
    title: item.title,
    summary: item.summary,
    format: item.format,
    bodyMarkdown: item.bodyMarkdown,
    coverAssetId: item.coverAssetId,
    posterAssetId: item.posterAssetId,
    imageAssetIds: item.imageAssetIds,
    authorMemberId: item.authorMemberId,
    authorDisplayName: item.authorDisplayName,
    contributors: item.contributors,
    tags: item.tags,
    periodStart: item.periodStart,
    periodEnd: item.periodEnd,
    stats: item.stats,
    version: item.version,
    publishedAt: item.publishedAt,
    updatedAt: item.updatedAt,
    contentHash: item.contentHash,
    assets: {}
  }
  statements.push(`INSERT INTO revisions (
  entity_type, entity_id, version, snapshot_json, content_hash, operator, created_at
) SELECT 'content', ${sql(item.id)}, ${sql(item.version)}, ${json(snapshot)}, ${sql(item.contentHash)}, 'legacy-import', ${sql(item.updatedAt)}
WHERE EXISTS (SELECT 1 FROM contents WHERE id = ${sql(item.id)})
ON CONFLICT(entity_type, entity_id, version) DO NOTHING;`)
}

await mkdir(dirname(outputPath), { recursive: true })
await writeFile(outputPath, `${statements.join('\n\n')}\n`)

console.log(JSON.stringify({
  output: outputPath,
  contents: contents.length,
  reports: fixture.reports.length,
  essays: fixture.essays.length
}, null, 2))
